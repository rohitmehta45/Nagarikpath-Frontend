// Helper function to get all provinces
export const getAllProvinces = () => {
  return nepalData.provinces.map(p => p.name);
};

// Helper function to get districts by province name
export const getDistrictsByProvince = (provinceName) => {
  const province = nepalData.provinces.find(p => p.name === provinceName);
  return province ? province.districts.map(d => d.name) : [];
};

// Helper function to get local levels by district name
export const getLocalLevelsByDistrict = (districtName) => {
  for (const province of nepalData.provinces) {
    const district = province.districts.find(d => d.name === districtName);
    if (district) {
      return district.localLevels;
    }
  }
  return [];
};

// Helper function to get province by district
export const getProvinceByDistrict = (districtName) => {
  for (const province of nepalData.provinces) {
    const found = province.districts.find(d => d.name === districtName);
    if (found) {
      return province.name;
    }
  }
  return null;
};

